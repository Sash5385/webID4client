import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell' });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('file://' + process.cwd() + '/dist/route7-2d.html');
await page.waitForTimeout(800);
await page.screenshot({ path: 'dist/shot1.png' });
await page.click('#sigR');
const gas = await page.$('#gas'); const b = await gas.boundingBox();
await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2); await page.mouse.down();
await page.waitForTimeout(6000);
await page.click('#turn').catch(() => {});
await page.screenshot({ path: 'dist/shot2.png' });
await page.waitForTimeout(5000);
await page.screenshot({ path: 'dist/shot3.png' });
await page.mouse.up();
console.log('errors:', errors);
await browser.close();
